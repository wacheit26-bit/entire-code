/** If the user picks a model before a brand is set, resolve brand from the model name. */
export function resolveBrandForPhoneName(name) {
  const trimmed = String(name ?? '').trim();
  if (!trimmed) return '';
  for (const [brand, names] of Object.entries(ADMIN_PHONES_BY_BRAND)) {
    if (names.includes(trimmed)) return brand;
  }
  return '';
}
